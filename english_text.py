CYRILLIC = re.compile("[А-Яа-яЁё]")
ORDERED = sorted(TEXT.items(), key=lambda pair: len(pair[0]), reverse=True)
IDENTITY_FIELDS = {"username", "first_name", "last_name", "nickname", "token_symbol",
                   "symbol", "mint", "address", "recipient", "signature"}


def translate(value):
    if isinstance(value, str) and CYRILLIC.search(value):
        for source, english in ORDERED:
            value = value.replace(source, english)
    return value


def payload(value):
    if isinstance(value, list):
        return [payload(item) for item in value]
    if isinstance(value, dict):
        result = {}
        for key, item in value.items():
            if key in IDENTITY_FIELDS:
                result[key] = item
            elif key == "reason" and isinstance(item, str) and CYRILLIC.search(item):
                result[key] = "Previous-language analysis. New analyses will use English."
            else:
                result[key] = payload(item)
        return result
    return translate(value)


@web.middleware
async def english_json_middleware(request, handler):
    response = await handler(request)
    if isinstance(response, web.Response) and response.content_type == "application/json" and response.body:
        try:
            data = json.loads(response.body)
        except (UnicodeDecodeError, json.JSONDecodeError):
            return response
        response.body = json.dumps(payload(data), ensure_ascii=False).encode("utf-8")
    return response
